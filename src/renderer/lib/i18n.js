let currentLang = (() => {
  try {
    const saved = localStorage.getItem("pi-desktop-lang");
    if (saved === "it" || saved === "en") return saved;
  } catch {}
  const nav = (navigator.language || "it").toLowerCase();
  return nav.startsWith("en") ? "en" : "it";
})();

const listeners = new Set();

function translate(key, vars = {}) {
  const dict = DICT[currentLang] || DICT.it;
  let str = dict[key];
  if (str == null) {
    const fallback = DICT.it[key] ?? DICT.en[key];
    if (fallback == null) return key;
    str = fallback;
  }
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`));
}

function getLang() { return currentLang; }

function setLang(lang) {
  if (lang !== "it" && lang !== "en") return;
  currentLang = lang;
  try { localStorage.setItem("pi-desktop-lang", lang); } catch {}
  document.documentElement.lang = lang;
  applyI18n();
  for (const cb of listeners) try { cb(lang); } catch {}
}

function onChange(cb) {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

function displayUserName(name) {
  const trimmed = String(name || "").trim();
  return trimmed || translate("userName.fallback");
}

function refreshUserNameUI(name) {
  const display = displayUserName(name);
  const profileName = document.querySelector("[data-profile-name]");
  const profileAvatar = document.querySelector("[data-profile-avatar]");
  const greeting = document.querySelector("[data-greeting]");
  if (profileName) profileName.textContent = display;
  if (profileAvatar) profileAvatar.textContent = (display[0] || "?").toUpperCase();
  if (greeting) greeting.textContent = translate("hero.greeting", { name: display });
}

function applyI18n() {
  // data-i18n, data-i18n-placeholder, data-i18n-title, data-i18n-aria
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    const htmlAllowed = el.hasAttribute("data-i18n-html");
    const val = translate(key);
    if (htmlAllowed) el.innerHTML = val;
    else el.textContent = val;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", translate(el.getAttribute("data-i18n-placeholder")));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", translate(el.getAttribute("data-i18n-title")));
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", translate(el.getAttribute("data-i18n-aria-label")));
  });
  // also update html lang
  document.documentElement.lang = currentLang;
  const savedName = window.piStore?.state?.settings?.userName;
  refreshUserNameUI(savedName);
}

// init lang attribute immediately
try { document.documentElement.lang = currentLang; } catch {}

window.i18n = { t: translate, getLang, setLang, applyI18n, onChange, refreshUserNameUI, displayUserName, DICT };
